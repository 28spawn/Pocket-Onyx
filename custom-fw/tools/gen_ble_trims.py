#!/usr/bin/env python3
"""gen_ble_trims.py - read this unit's stored radio calibration from a verified flash backup and write it as a C header.

    python custom-fw/tools/gen_ble_trims.py [--dump custom-fw/qa/backups/unit1_v105/dump1.bin]

The imported BLE stack will only start the radio with the four RF records of the unit's SDK "VM" store (ids 106 crystal trims, 107 PA, 108 PA digital gain,
187 RF table: 2 + 7 + 20 + 68 = 97 bytes). This unit keeps them in the VM area at 0xB5000 (the stock firmware wrote them at the factory / first boot); our firmware
cannot read that area at run time, so they are taken from the backup, offline, and compiled in. OFFLINE and READ-ONLY: nothing touches the unit.

Output: custom-fw/src/board/ble_platform/ble_trims_unit.h (calibration table header, generated per device). Without it
the firmware builds with PA_BLE but refuses to start the radio ("no cal").

Format (third_party/optimist_ble/src/ble_vm.h): area starts 55 AA AA 55; records from area+4: [check = low byte of CRC-16/XMODEM of the data]
[id 7:0][id 11:8 | length 3:0 << 4][length 11:4] then the data; the log ends at the first record that fails its check; the last record of an id wins.
Record 187 carries its own CRC-16/XMODEM (little-endian) over its first 64 bytes, then 00 00.
"""
import argparse
import sys
from pathlib import Path

VM_CANDIDATES = (0xB5000, 0xE8000, 0xE7000, 0x93000, 0x95000)
WANT = ((106, 2), (107, 7), (108, 20), (187, 68))


def crc16x(b):
    c = 0
    for x in b:
        c ^= x << 8
        for _ in range(8):
            c = ((c << 1) ^ 0x1021) & 0xFFFF if c & 0x8000 else (c << 1) & 0xFFFF
    return c


def scan(d, area, size=0x8000):
    if d[area:area + 4] != bytes([0x55, 0xAA, 0xAA, 0x55]):
        return None
    off, last = area + 4, {}
    while off + 4 <= min(len(d), area + size):
        chk, idl, b2, b3 = d[off], d[off + 1], d[off + 2], d[off + 3]
        rid = idl | ((b2 & 0x0F) << 8)
        ln = (b2 >> 4) | (b3 << 4)
        if ln == 0 or off + 4 + ln > area + size:
            break
        data = d[off + 4:off + 4 + ln]
        if (crc16x(data) & 0xFF) != chk:
            break
        last[rid] = bytes(data)
        off += 4 + ln
    return last


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    here = Path(__file__).resolve().parent.parent
    ap.add_argument("--dump", default=str(here / "qa" / "backups" / "unit1_v105" / "dump1.bin"))
    ap.add_argument("--out", default=str(here / "src" / "board" / "ble_platform" / "ble_trims_unit.h"))
    a = ap.parse_args()
    d = Path(a.dump).read_bytes()
    for area in VM_CANDIDATES:
        recs = scan(d, area)
        if recs and all(i in recs and len(recs[i]) == n for i, n in WANT):
            break
    else:
        print("no VM area with all four records (106, 107, 108, 187) in", a.dump)
        return 1
    r187 = recs[187]
    ok187 = crc16x(r187[:64]) == (r187[64] | r187[65] << 8) and r187[66:68] == b"\x00\x00"
    print(f"VM area {area:#x}: records " + ", ".join(f"{i} ({len(recs[i])} B)" for i, _ in WANT) + f"; record 187 inner CRC {'ok' if ok187 else 'FAILS'}")
    if not ok187:
        return 1
    lines = ["/* GENERATED by tools/gen_ble_trims.py - local radio calibration parameters. */",
             "#pragma once", "#define PA_BLE_TRIMS_PRESENT 1", f"#define PA_BLE_TRIMS_AREA {area:#x}u"]
    for i, _ in WANT:
        body = ", ".join(f"0x{b:02X}" for b in recs[i])
        lines.append(f"static const unsigned char pa_ble_trim_x{i}[{len(recs[i])}] = {{ {body} }};")
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())

