/* custom-fw/src/fx/fx_drive.c - the DRV block: six drive / fuzz pedals.
 *
 *   0 TS-808     Ibanez TS808: 720 Hz high-passed gain path into symmetric soft diodes,
 *                ADDED to the full-range clean signal (the op-amp's unity path)
 *   1 KLON       Klon Centaur: clean blend that falls as GAIN rises + soft germanium clip
 *   2 OCD        Fulltone OCD: asymmetric MOSFET clipping (even harmonics)
 *   3 RAT        ProCo RAT: very high op-amp gain, slew-limited, hard silicon diodes
 *   4 BIG MUFF   EHX Big Muff Pi: two cascaded clipping stages + the mid-scoop tone stack
 *   5 FUZZ FACE  Dallas Arbiter Fuzz Face: biased, asymmetric germanium saturation
 *
 * Knobs (set_param ids): 0 GRIT, 1 TONE, 2 LEVEL, 3 model.
 *   GRIT   gain, exponential between each pedal's minimum and maximum (TS 6x..120x,
 *          RAT 2x..400x, ...). It was 1x..12x on every model - a TS at full GRIT only
 *          reached 10 % THD.
 *   TONE   a treble roll-off 600 Hz .. 10 kHz; on the BIG MUFF the low-pass / high-pass
 *          blend that scoops the mids.
 *   LEVEL  0 % silent, 50 % unity, 100 % +12 dB (square law). Every model and GRIT
 *          setting is loudness-matched, so at 50 % the pedal is as loud as bypass.
 *          (0 % used to mean full volume, and the models were up to 11 dB apart.)
 *
 * The clipping runs 4x oversampled (dsp/pa_oversample.h, ~100 dB image rejection; the
 * old 2x stage left an alias 26 dB under a high note). Each model also rolls off its
 * gain path before the clipper, the way the real circuits' op-amp bandwidth does: it is
 * part of the sound and it keeps the clipped edges, hence the aliasing, down.
 *
 * Float throughout: the AC791N has a single-precision FPU. In and out are Q21.
 */

