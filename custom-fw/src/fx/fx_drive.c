/* ---- the oversampling filters, run a whole block per section ------------------------------------------------------------------------
 * The halfband filters of dsp/pa_oversample.h are polyphase chains of first-order allpass sections. The old code ran them one sample at a
 * time, and every section kept two memory words (x1, y1) that were loaded and stored for each sample: on this core a load from SRAM costs
 * 7 to 10 cycles, so the filters spent most of the drive's time moving state around. Here every section runs over the whole block with its
 * coefficient and its ONE memory word in registers. The data flow is exactly the old one: up 1x -> 2x with the 8-coefficient pair, 2x -> 4x
 * with the 3-coefficient pair, and the mirror image down. */
typedef struct { float x1[PA_HB1_N], y1[PA_HB1_N], x2[PA_HB2_N], y2[PA_HB2_N]; } drv_up_t;
typedef struct { float x1[PA_HB1_N], y1[PA_HB1_N], x2[PA_HB2_N], y2[PA_HB2_N]; float d1, d2; } drv_dn_t;

/* One allpass section over a block: y[n] = c (x[n] - y[n-1]) + x[n-1], exactly the arithmetic of pa_hb_branches() (so the output is
 * identical to the old code's, which matters for the antialiased clippers: their divide amplifies any rounding difference). The two
 * memory words stay in registers for the whole block. */
static inline void ap_run(float *v, int n, int stride, float c, float *px1, float *py1) {
    float x1 = *px1, y1 = *py1;
    for (int i = 0; i < n; i++) {
        float *p = v + i * stride;
        const float x = *p;
        const float y = c * (x - y1) + x1;
        x1 = x; y1 = y;
        *p = y;
    }
    *px1 = x1; *py1 = y1;
}

/* din[n] -> u[os * n] in time order; tmp needs 2n floats */
static void drv_up_block(drv_up_t *f, const float *din, int n, int os, float *u, float *tmp) {
    float *b0 = tmp, *b1 = tmp + n;
    for (int i = 0; i < n; i++) { b0[i] = din[i]; b1[i] = din[i]; }
    for (int k = 0; k < PA_HB1_N; k += 2) ap_run(b0, n, 1, pa_hb1_c[k], &f->x1[k], &f->y1[k]);      /* branch 0: even coefficients */
    for (int k = 1; k < PA_HB1_N; k += 2) ap_run(b1, n, 1, pa_hb1_c[k], &f->x1[k], &f->y1[k]);      /* branch 1: odd coefficients */
    if (os == 2) {
        for (int i = 0; i < n; i++) { u[2 * i] = b0[i]; u[2 * i + 1] = b1[i]; }
        return;
    }
    /* the 2x stream is b0[0], b1[0], b0[1], b1[1] ...; the second stage turns each of its samples into two */
    for (int i = 0; i < n; i++) {
        u[4 * i]     = b0[i]; u[4 * i + 1] = b0[i];
        u[4 * i + 2] = b1[i]; u[4 * i + 3] = b1[i];
    }
    const int m = 2 * n;
    for (int k = 0; k < PA_HB2_N; k += 2) ap_run(u,     m, 2, pa_hb2_c[k], &f->x2[k], &f->y2[k]);   /* elements u[2t]: branch 0 */
    for (int k = 1; k < PA_HB2_N; k += 2) ap_run(u + 1, m, 2, pa_hb2_c[k], &f->x2[k], &f->y2[k]);   /* elements u[2t+1]: branch 1 */
}

/* w[os * n] -> y[n]; tmp needs 4n floats */
static void drv_dn_block(drv_dn_t *f, const float *w, int n, int os, float *y, float *tmp) {
    const float *R;                                  /* the 2x stream, 2n samples */
    float *E1, *O1;
    if (os == 4) {
        const int m = 2 * n;
        float *E = tmp, *O = tmp + m;
        for (int i = 0; i < n; i++) {
            E[2 * i]     = w[4 * i];
            O[2 * i]     = (i == 0) ? f->d2 : w[4 * i - 1];
            E[2 * i + 1] = w[4 * i + 2];
            O[2 * i + 1] = w[4 * i + 1];
        }
        f->d2 = w[4 * n - 1];
        for (int k = 0; k < PA_HB2_N; k += 2) ap_run(E, m, 1, pa_hb2_c[k], &f->x2[k], &f->y2[k]);
        for (int k = 1; k < PA_HB2_N; k += 2) ap_run(O, m, 1, pa_hb2_c[k], &f->x2[k], &f->y2[k]);
        for (int t = 0; t < m; t++) E[t] = 0.5f * (E[t] + O[t]);
        R = E;
        E1 = O; O1 = O + n;                          /* O is free now */
    } else {
        R = w;
        E1 = tmp; O1 = tmp + n;
    }
    for (int i = 0; i < n; i++) {
        E1[i] = R[2 * i];
        O1[i] = (i == 0) ? f->d1 : R[2 * i - 1];
    }
    f->d1 = R[2 * n - 1];
    for (int k = 0; k < PA_HB1_N; k += 2) ap_run(E1, n, 1, pa_hb1_c[k], &f->x1[k], &f->y1[k]);
    for (int k = 1; k < PA_HB1_N; k += 2) ap_run(O1, n, 1, pa_hb1_c[k], &f->x1[k], &f->y1[k]);
    for (int i = 0; i < n; i++) y[i] = 0.5f * (E1[i] + O1[i]);
}

typedef struct {
    drive_type_t type;
    float grit, tone, level;          /* knobs 0..1 */

    /* derived */
    float gain;                       /* gain-path gain */
    float hp_a, lp_a;                 /* gain-path filters (one-pole) */
    float tone_a;                     /* tone low-pass coefficient */
    float muff_lp_a, muff_hp_a;       /* Big Muff tone stack */
    float clean;                      /* clean-path gain (TS: 1, Klon: falls with GRIT) */
    float out_gain;                   /* loudness match x LEVEL */

    /* state */
    float hp_x1, hp_y1, lp_y1;
    float tone_y1, mlp_y1, mhp_x1, mhp_y1;
    float dc_x1, dc_y1;
    drv_up_t      up_d, up_c;         /* the gain path and the clean path */
    drv_dn_t      dn;
    adaa_t aa2;                       /* BIG MUFF's second stage */
    float  muff_mid;                  /* BIG MUFF inter-stage roll-off (4x rate) */
    adaa_t aa;                        /* ADAA memory (RAT / BIG MUFF), at the 4x rate */

    /* Klon clean-path dedicated warm filtering */
    float  cl_hp_a, cl_lp_a;
    float  cl_hp_x1, cl_hp_y1, cl_lp_y1;
    float  last_pk;                   /* the clipper input's peak in the last block */
    uint8_t os_now;                   /* the oversampling in use: 2 or 4 (0 = not chosen yet) */
    uint8_t os_hold;                  /* blocks the level has stayed low (before going back to 2x) */
} drive_state_t;

